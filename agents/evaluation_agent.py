"""
Evaluation Agent - Dedicated to critique, reflection, and evaluating outputs.
"""

from agents.base_agent import BaseAgent
from config.settings import settings
from langchain_core.prompts import PromptTemplate
from pydantic import BaseModel, Field

class EvaluationOutput(BaseModel):
    passed: bool = Field(description="true if it's excellent and fully answers the query, false if it needs revision", alias="pass")
    score: int = Field(description="1 to 10")
    feedback: str = Field(description="Detailed string explaining exactly what is missing, wrong, or needs to be added.")

class EvaluationAgent(BaseAgent):
    """Evaluates the quality of research, analysis, and reports to guide reflection loops."""

    def __init__(self, llm_provider: str = None):
        super().__init__("EvaluationAgent", llm_provider=llm_provider)
        
        # Initialize LLM manually to avoid importing heavy chains right away if not needed
        provider = (llm_provider or settings.llm_provider).lower()
        
        self.llm = self._init_llm(provider)

    def _init_llm(self, provider: str):
        provider = (provider or settings.llm_provider).lower()
        if provider in ("gemini", "google"):
            if not settings.google_api_key:
                raise ValueError("GOOGLE_API_KEY is required for Gemini provider.")
            from langchain_google_genai import ChatGoogleGenerativeAI
            return ChatGoogleGenerativeAI(
                model=settings.llm_model,
                google_api_key=settings.google_api_key,
                temperature=0.2,
                timeout=120,
            )
        elif provider == "openai":
            if not settings.openai_api_key:
                raise ValueError("OPENAI_API_KEY is required for OpenAI provider.")
            from langchain_openai import ChatOpenAI
            return ChatOpenAI(
                model=settings.openai_model,
                openai_api_key=settings.openai_api_key,
                temperature=0.2
            )
        else: # ollama fallback
            from langchain_ollama import ChatOllama
            return ChatOllama(
                model=settings.ollama_model,
                base_url=settings.ollama_host,
                temperature=0.2
            )

    def execute(self, task: dict) -> dict:
        """
        Evaluate an output.

        Task keys:
            - output_to_evaluate (str): The text generated by another agent.
            - original_query (str): The original user query.
            - task_type (str): Type of task being evaluated (e.g., 'report', 'analysis', 'research')
        """
        output = task.get("output_to_evaluate", "")
        query = task.get("original_query", "")
        task_type = task.get("task_type", "general")

        if not output:
            return {"status": "error", "message": "No output provided to evaluate."}

        self.log(f"Evaluating {task_type} for query: '{query}'")

        prompt = PromptTemplate.from_template(
            """You are a strict academic evaluator. Your job is to critique an AI-generated output based on the user's original query.

            Original Query: {query}
            Task Type: {task_type}

            Output to Evaluate:
            {output}
            """
        )

        try:
            from config.settings import CallBudgetTracker
            CallBudgetTracker.record_call("EvaluationAgent")

            structured_llm = self.llm.with_structured_output(EvaluationOutput)
            chain = prompt | structured_llm
            
            response = chain.invoke({
                "query": query,
                "task_type": task_type,
                "output": output
            })
            
            self.log(f"Evaluation complete. Passed: {response.passed}, Score: {response.score}/10")
            
            return {
                "status": "success",
                "pass": response.passed,
                "score": response.score,
                "feedback": response.feedback,
            }
            
        except Exception as e:
            self.log(f"Evaluation parsing failed: {e}", level="error")
            return {
                "status": "error",
                "pass": False,
                "score": 0,
                "feedback": f"Failed to evaluate due to parsing error: {e}",
            }
